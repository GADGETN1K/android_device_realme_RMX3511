"""Turn the stock (platform 31.0) vendor_sepolicy.cil into .te statements for
the types the stock vendor adds on top of AOSP. Usage:
  cil2te.py stock_vendor.cil our_plat_pub_versioned.cil our_vendor.cil outdir"""
import re, sys, os, collections
stock, ourpub, ourven, out = sys.argv[1:5]

def sexps(text):
    # top-level S-expressions -> nested lists of str
    tok = re.findall(r'\(|\)|"[^"]*"|[^\s()]+', re.sub(r';[^\n]*', '', text))
    stack=[[]]
    for t in tok:
        if t=='(':
            stack.append([])
        elif t==')':
            e=stack.pop(); stack[-1].append(e)
        else:
            stack[-1].append(t)
    return stack[0]

S = sexps(open(stock).read())
P = sexps(open(ourpub).read())
V = sexps(open(ourven).read())

def names(stmts, kinds):
    r=set()
    for s in stmts:
        if s and s[0] in kinds and isinstance(s[1],str): r.add(s[1])
    return r
strip = lambda n, v: re.sub(r'_%s$' % v, '', n)

plat = {strip(n,'202504') for n in names(P, ('type','typeattribute'))}
ours = names(V, ('type','typeattribute'))
known_ours = plat | ours | {'self'}

stock_types = names(S, ('type',))
stock_attrs = names(S, ('typeattribute',))
new_types = {t for t in stock_types if t not in known_ours and not t.endswith('_31_0')}
new_attrs = {a for a in stock_attrs if a not in known_ours and not a.endswith('_31_0')
             and not a.startswith('base_typeattr_')}
known = known_ours | new_types | new_attrs

dropped = collections.Counter()
def m(n):
    """map a stock name to an A16 name, or None"""
    if not isinstance(n,str): return None
    n = strip(n,'31_0')
    if n.startswith('base_typeattr_'): return None
    return n if n in known else None

def perms(p):
    return ' '.join(p) if isinstance(p,list) else p
def xperms(p):
    out=[]
    for x in p:
        if isinstance(x,list):
            if x and x[0]=='range': out.append('%s-%s'%(x[1],x[2]))
            else: out.extend(xperms(x))
        else: out.append(x)
    return out

te=collections.defaultdict(list)   # key: subject -> lines
def key(s): return s if s in new_types or s in new_attrs else '_platform_subjects'
for t in sorted(new_types): te[t].insert(0,'type %s;'%t)
attr_lines=['attribute %s;'%a for a in sorted(new_attrs)]

for s in S:
    if not s: continue
    k=s[0]
    if k in ('allow','dontaudit'):
        src,tgt,(cls,pm)=m(s[1]),m(s[2]),s[3]
        if not src or not tgt: dropped[k]+=1; continue
        if k=='dontaudit': continue
        if src not in new_types|new_attrs and tgt not in new_types|new_attrs: dropped['allow_platform_only']+=1; continue
        te[key(src)].append('allow %s %s:%s { %s };'%(src,tgt,cls,perms(pm)))
    elif k=='allowx':
        src,tgt=m(s[1]),m(s[2]); op,cls,xp=s[3][0],s[3][1],s[3][2]
        if not src or not tgt: dropped[k]+=1; continue
        if src not in new_types|new_attrs and tgt not in new_types|new_attrs: dropped['allowx_platform_only']+=1; continue
        te[key(src)].append('allowxperm %s %s:%s %s { %s };'%(src,tgt,cls,op,' '.join(xperms(xp))))
    elif k=='typetransition':
        a=[m(x) if isinstance(x,str) and not x.startswith('"') else x for x in s[1:]]
        if len(s)==5:   # src tgt class result
            src,tgt,cls,res=m(s[1]),m(s[2]),s[3],m(s[4]); name=None
        else:           # src tgt class "name" result
            src,tgt,cls,name,res=m(s[1]),m(s[2]),s[3],s[4],m(s[5])
        if not (src and tgt and res): dropped[k]+=1; continue
        if res not in new_types: dropped['tt_platform_only']+=1; continue
        te[key(src)].append('type_transition %s %s:%s %s%s;'%(src,tgt,cls,res,(' '+name) if name else ''))
    elif k=='typeattributeset':
        a=m(s[1]) if not s[1].startswith('base_typeattr_') else None
        if not a or not isinstance(s[2],list) or (s[2] and s[2][0] in ('and','or','not','all')): dropped[k]+=1; continue
        for mem in s[2]:
            mm=m(mem) if isinstance(mem,str) else None
            if mm and mm in new_types: te[mm].append('typeattribute %s %s;'%(mm,a))
            elif mm and mm in new_attrs and a not in new_attrs: te[mm].append('# attribute %s is in %s'%(mm,a))
    elif k=='genfscon':
        pass
os.makedirs(out,exist_ok=True)
hdr='# Generated by tools/cil2te.py from the stock RMX3511 vendor_sepolicy.cil\n# (platform 31.0). Do not edit by hand; fix the generator or add rules in\n# a separate file.\n\n'
with open(os.path.join(out,'attributes'),'w') as f: f.write(hdr+'\n'.join(attr_lines)+'\n')
body=[]
for k in sorted(te):
    seen=[];[seen.append(l) for l in te[k] if l not in seen]
    body.append('\n'.join(seen))
with open(os.path.join(out,'stock_vendor.te'),'w') as f: f.write(hdr+'\n\n'.join(body)+'\n')
# genfs
g=[]
for s in S:
    if s and s[0]=='genfscon':
        fs,path,ctx=s[1],s[2],s[3]; t=m(ctx[2])
        if t and t in new_types: g.append('genfscon %s %s u:object_r:%s:s0'%(fs,path.strip('"'),t))
with open(os.path.join(out,'genfs_contexts'),'w') as f: f.write(hdr+'\n'.join(g)+'\n')
open(os.path.join(out,'.known_types'),'w').write('\n'.join(sorted(known))+'\n')
print('new types',len(new_types),'new attrs',len(new_attrs))
print('dropped',dict(dropped))
print('te lines',sum(len(v) for v in te.values()),'genfs',len(g))
